// Command genicons turns the pinned Material Symbols subset in
// internal/uiassets/icons into a single SVG sprite.
//
// It is a development-time tool: the generated sprite is committed, so a
// normal `go build` never needs network access or this program.
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	manifestPath = "internal/uiassets/icons/manifest.txt"
	sourceDir    = "internal/uiassets/icons/src/rounded"
	outputPath   = "internal/uiassets/dist/icons.svg"
	licenseSrc   = "internal/uiassets/icons/src/LICENSE.txt"
	licenseDst   = "internal/uiassets/dist/icons.LICENSE.txt"
	faviconPath  = "internal/uiassets/dist/favicon.svg"
	upstream     = "material-symbols@0.48.2 (Apache-2.0)"
)

var svgRe = regexp.MustCompile(`(?s)<svg[^>]*viewBox="([^"]+)"[^>]*>(.*)</svg>`)

func main() {
	entries, err := readManifest(manifestPath)
	if err != nil {
		fail(err)
	}

	var symbols []string
	for _, e := range entries {
		data, err := os.ReadFile(filepath.Join(sourceDir, e.source+".svg"))
		if err != nil {
			fail(fmt.Errorf("read %s: %w", e.source, err))
		}
		m := svgRe.FindSubmatch(data)
		if m == nil {
			fail(fmt.Errorf("%s: no <svg viewBox> found", e.source))
		}
		inner := strings.TrimSpace(string(m[2]))
		// Strip any presentation fill so CSS can colour the icon.
		inner = strings.ReplaceAll(inner, ` fill="#000000"`, "")
		symbols = append(symbols, fmt.Sprintf(
			`  <symbol id="i-%s" viewBox="%s">%s</symbol>`,
			e.local, m[1], inner,
		))
	}

	var b strings.Builder
	b.WriteString("<!-- Generated by `go run ./internal/uiassets/genicons`; DO NOT EDIT.\n")
	b.WriteString("     Source: " + upstream + ". License: internal/uiassets/dist/icons.LICENSE.txt. -->\n")
	b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg">` + "\n")
	for _, s := range symbols {
		b.WriteString(s + "\n")
	}
	b.WriteString("</svg>\n")

	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(outputPath, []byte(b.String()), 0o644); err != nil {
		fail(err)
	}
	if err := copyFile(licenseSrc, licenseDst); err != nil {
		fail(err)
	}
	if err := writeFavicon(); err != nil {
		fail(err)
	}
	fmt.Printf("generated %s (%d icons)\n", outputPath, len(symbols))
}

type entry struct {
	local  string
	source string
}

func readManifest(path string) ([]entry, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var out []entry
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 2 {
			return nil, fmt.Errorf("%s: expected 'local source', got %q", path, line)
		}
		out = append(out, entry{local: fields[0], source: fields[1]})
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	for _, e := range out {
		if seen[e.local] {
			return nil, fmt.Errorf("duplicate icon name %q", e.local)
		}
		seen[e.local] = true
	}
	sort.Slice(out, func(i, j int) bool { return out[i].local < out[j].local })
	return out, nil
}

func writeFavicon() error {
	data, err := os.ReadFile(filepath.Join(sourceDir, "monitoring-fill.svg"))
	if err != nil {
		return err
	}
	m := svgRe.FindSubmatch(data)
	if m == nil {
		return fmt.Errorf("monitoring-fill.svg: no <svg viewBox> found")
	}
	inner := strings.ReplaceAll(strings.TrimSpace(string(m[2])), ` fill="#000000"`, "")
	out := `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 960 960">` +
		`<rect width="960" height="960" rx="220" fill="#0b57d0"/>` +
		`<g transform="translate(0 960)" fill="#ffffff">` + inner + `</g></svg>\n`
	return os.WriteFile(faviconPath, []byte(out), 0o644)
}

func copyFile(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0o644)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genicons:", err)
	os.Exit(1)
}
